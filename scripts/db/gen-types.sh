#!/usr/bin/env bash
# Regenerates src/services/supabase/database.types.ts from the LOCAL database (supabase start must be running,
# and the migrations applied). Run it after every migration that changes a table; `npm run build` then
# type-checks the repositories against the real schema.
set -euo pipefail

root="$(cd "$(dirname "$0")/../.." && pwd)"
target="$root/src/services/supabase/database.types.ts"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

supabase gen types typescript --local >"$tmp"
{
  echo '// Generated by `npm run db:types` (supabase gen types typescript --local) from the migrations. Do not edit by hand.'
  cat "$tmp"
} >"$target"
cd "$root" && npx prettier --write "$target" >/dev/null
echo "wrote $target"
